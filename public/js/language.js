function setLanguage(lang) {
  localStorage.setItem('userLanguage', lang);
  applyAutoTranslation(lang);
}

// 3. HTML-İ DƏYİŞMƏDƏN AVTOMATİK MƏTN TƏRCÜMƏ EDƏN SKRİPT
function applyAutoTranslation(lang) {
  // Səhifədəki bütün mətn elementlərini (DOM düyünlərini) gəzirik
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    null,
    false
  );

  let node;
  while ((node = walker.nextNode())) {
    const text = node.nodeValue.trim();
    if (!text) continue;

    // Əgər mətn lüğətimizdə varsa, dəyişdiririk
    for (const [originalAzText, targetLangs] of Object.entries(dictionary)) {
      if (text === originalAzText || (node.parentNode && node.parentNode.dataset.originalText === originalAzText)) {
        if (!node.parentNode.dataset.originalText) {
          node.parentNode.dataset.originalText = originalAzText; // Orijinal azərbaycan mətni yadda saxlayırıq
        }

        if (lang === 'az') {
          node.nodeValue = node.parentNode.dataset.originalText;
        } else if (targetLangs[lang]) {
          node.nodeValue = targetLangs[lang];
        }
        break;
      }
    }
  }

  // Input və Textarea-ların placeholder-lərini tərcümə edirik
  const inputs = document.querySelectorAll('input, textarea');
  inputs.forEach(input => {
    const placeholderText = input.placeholder.trim();
    if (!placeholderText) return;

    for (const [originalAzText, targetLangs] of Object.entries(dictionary)) {
      if (placeholderText === originalAzText || input.dataset.originalPlaceholder === originalAzText) {
        if (!input.dataset.originalPlaceholder) {
          input.dataset.originalPlaceholder = originalAzText;
        }

        if (lang === 'az') {
          input.placeholder = input.dataset.originalPlaceholder;
        } else if (targetLangs[lang]) {
          input.placeholder = targetLangs[lang];
        }
        break;
      }
    }
  });
}

